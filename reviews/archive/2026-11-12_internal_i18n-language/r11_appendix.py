"""Build APPENDIX.md: every finding of the read-through (readthrough/*.tsv) with an id R<chunk>-<row>, grouped by
catalogue, plus the mechanical lists (plural agreement, Latin K, decimal points, English identifiers in placeholders).
Run: python3 -I r11_appendix.py   (writes APPENDIX.md next to this script)
"""
import csv, glob, json, os, re, sys
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from r00_load import load  # noqa: E402

rows = []
for f in sorted(glob.glob(os.path.join(HERE, "readthrough", "reader_chunk_*.tsv"))):
    chunk = re.search(r"chunk_(\d\d)", f).group(1)
    with open(f, encoding="utf-8") as fh:
        lines = fh.read().splitlines()
    for i, line in enumerate(lines[1:], 1):
        p = line.split("\t")
        if len(p) != 7:
            continue
        rows.append({"id": f"R{chunk}-{i:03d}", "kind": p[0], "sev": p[1], "cat": p[2], "msgid": p[3], "ru": p[4],
                     "problem": p[5], "proposed": p[6]})


def esc(s):
    return s.replace("\n", " ").strip()


out = []
w = out.append
w("# Appendix to the review 2026-11-12 i18n-language: full lists")
w("")
w("Generated by `r11_appendix.py` from `readthrough/*.tsv` (the read-through of every catalogue entry, nine readers, one "
  "per chunk) and from the mechanical scripts `r01`–`r10` (their `.out` files hold the raw output). Ids `R<chunk>-<row>` "
  "point to the row of `readthrough/reader_chunk_<chunk>_*.tsv`. Severity: error / should-fix / nit. The review's "
  "verdicts on some rows (overruled or merged) are in REVIEW.md § «Reader rows overruled».")
w("")
c = Counter((r["kind"], r["sev"]) for r in rows)
kinds = sorted({k for k, _ in c})
w("## A. Counts of the read-through")
w("")
w("| kind | error | should-fix | nit | total |")
w("|---|---|---|---|---|")
for k in kinds:
    e, s, n = c[(k, "error")], c[(k, "should-fix")], c[(k, "nit")]
    w(f"| {k} | {e} | {s} | {n} | {e + s + n} |")
tot = Counter(r["sev"] for r in rows)
w(f"| **all** | **{tot['error']}** | **{tot['should-fix']}** | **{tot['nit']}** | **{len(rows)}** |")
w("")
w("## B. Read-through findings by catalogue")
order = ["engine", "framework"] + sorted({r["cat"] for r in rows} - {"engine", "framework"})
sevrank = {"error": 0, "should-fix": 1, "nit": 2}
for cat in order:
    rs = [r for r in rows if r["cat"] == cat]
    if not rs:
        continue
    w("")
    w(f"### {cat} ({len(rs)})")
    w("")
    for r in sorted(rs, key=lambda r: (sevrank.get(r["sev"], 3), r["kind"] != "PATTERN", r["id"])):
        w(f"- **{r['id']}** · {r['sev']} · {r['kind']} · `{esc(r['msgid'])}`")
        w(f"  - now: {esc(r['ru'])}")
        w(f"  - problem: {esc(r['problem'])}")
        w(f"  - proposed: {esc(r['proposed'])}")

# C. plural agreement (mechanical)
E = load()
NOUNS = set("""точек точки точках точкам узлов узла узлах шагов шага пар раза раз импульсов значений частиц частицам
отсчётов объектов строк символов пакетов лет атомов молекул замеров замер блоков ячеек щелей чисел функций фотонов фотон
углов пикселей пикселя пикселях пикс компонент графиков запуска""".split())
w("")
w("## C. Plural agreement: a number placeholder followed by a counted noun, entry without plural forms")
w("")
w("A count that can end in 1 or 2–4 needs plural forms (or the «noun: {n}» order). Entries whose count is always large "
  "(grid sizes in genitive after «из», «в N раз») are listed too; only nominative/accusative constructions are wrong "
  "for most values.")
w("")
for x in E:
    if x["forms"]:
        continue
    for m in re.finditer(r"\{(\w+)(?::([^{}]*))?\}\s+([а-яё]+)", x["ru"]):
        if m.group(3) in NOUNS:
            w(f"- [{x['cat']}] `{x['msgid'][:160]}` — «{m.group(0)}»")
            break
w("")
w("## D. Latin «K» for kelvin in Russian (should be «К»)")
w("")
for x in E:
    s = re.sub(r"\{[^}]*\}", "0", x["ru"])
    if re.search(r"(?<![\w-])\d+(?:[.,]\d+)?\s?K\b", s):
        w(f"- [{x['cat']}] `{x['msgid'][:120]}` — {x['ru'][:120]}")
w("")
w("## E. Decimal point in Russian prose (outside references and identifiers)")
w("")
for x in E:
    s = re.sub(r"\{[^}]*\}", "", x["ru"])
    s = re.sub(r"`[^`]*`|arXiv:\S+|\b\d+\.\d+\.\d+\b|https?://\S+", "", s)
    s = re.sub(r"\((\d+\.\d+)\)|ур\. [\d.,–\s]+|§[\d.–]+|гл\. [\d.]+|разд\. [\d.]+|(Licence|BY-NC-SA) \d\.\d", "", s)
    s = re.sub(r"\b[A-Z][\w&.,' -]{2,80}\(\d{4}\)[^;]*", "", s)
    if re.search(r"(?<![\w.§])\d+\.\d+(?![\w.])", s):
        w(f"- [{x['cat']}] `{x['msgid'][:110]}` — {x['ru'][:160]}")
w("")
w("## F. Russian «2-D/3-D» against «2D/3D» (counts per catalogue)")
w("")
for name, rx in (("2-D / 3-D", r"\b[123]-D\b"), ("2D / 3D", r"\b[123]D\b")):
    cc = Counter()
    for x in E:
        n = len(re.findall(rx, re.sub(r"\{[^}]*\}", "", x["ru"])))
        if n:
            cc[x["cat"]] += n
    w(f"- {name}: {sum(cc.values())} — " + ", ".join(f"{k} {v}" for k, v in sorted(cc.items())))
w("")
w("## G. Term renderings across catalogues")
w("")
w("The full tables (rendering → count per catalogue, entries with other renderings, short labels) are in "
  "`r04_terms.out`; the placeholder arguments that are plain strings in the code are in `r07_placeholder_args.out`; "
  "the Russian literals removed by the conversion that do not reappear verbatim in the catalogues are in `r05_drift.out`.")
with open(os.path.join(HERE, "APPENDIX.md"), "w", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")
print(len(rows), "read-through rows;", sum(1 for l in out if l.startswith("- [")), "mechanical rows")
