def norm(s):
    return s.lower().replace("ё", "ё")


out_unknown = defaultdict(list)
for term, rends in TERMS.items():
    rx = re.compile(term, re.I)
    xs = [x for x in E if rx.search(x["msgid"])]
    if not xs:
        continue
    print("=" * 100)
    print(f"TERM {term}   entries: {len(xs)}")
    tab = defaultdict(Counter)
    unknown = []
    for x in xs:
        ru = norm(x["ru"])
        found = False
        for name, rr in rends.items():
            if re.search(rr, ru):
                tab[name][x["cat"]] += 1
                found = True
        if not found:
            unknown.append(x)
    for name in rends:
        if tab[name]:
            tot = sum(tab[name].values())
            print(f"  {name:22s} {tot:4d}  " + ", ".join(f"{c}:{n}" for c, n in sorted(tab[name].items())))
    print(f"  (none of these)        {len(unknown):4d}")
    for x in unknown[:12]:
        print(f"     [{x['cat']}] {x['msgid'][:110]}\n         -> {x['ru'][:140]}")
    short = [x for x in xs if len(x["msgid"].split()) <= 6]
    if short:
        print("  short labels:")
        for x in short[:60]:
            print(f"     [{x['cat']}] {x['msgid']}  ->  {x['ru']}")
